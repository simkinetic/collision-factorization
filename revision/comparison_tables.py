"""Tables for the two Sec. 5.2 checks stated in prose so far.
(1) Hanke-Torrilhon Maxwell impact-tensor comparison, grouped by l1 (from hanke_torrilhon_maxwell_comparison.csv).
(2) Maxwell degree-rule check: largest forbidden entry of R vs quadrature padding (from maxwell_degree_rule.csv)."""
import csv, os, collections
here=os.path.dirname(os.path.abspath(__file__)); data=os.path.join(here,'data'); tabs=os.path.join(here,'tables')
def sci(x):
    if x==0: return "$0$"
    e=int(f"{x:e}".split('e')[1]); m=x/10**e
    return f"${m:.1f}\\times 10^{{{e}}}$"
# (1)
rows=list(csv.DictReader(open(os.path.join(data,'hanke_torrilhon_maxwell_comparison.csv'))))
g=collections.defaultdict(lambda: {'ch':0,'n':0,'res':0.0,'factors':set(),'triples':set()})
for r in rows:
    l1=int(r['l1']); d=g[l1]; d['ch']+=1; d['n']+=int(r['n_entries']); d['res']=max(d['res'],float(r['rel_residual']))
    d['factors'].add(round(float(r['scale_factor']),9)); d['triples'].add(tuple(sorted((int(r['l1']),int(r['l2']),int(r['l3'])))))
tot_ch=sum(d['ch'] for d in g.values()); tot_n=sum(d['n'] for d in g.values()); tot_res=max(d['res'] for d in g.values())
# symmetry: number of distinct factors over all channels vs number of distinct sorted triples
allf=set(); allt=set()
for r in rows: allf.add(round(float(r['scale_factor']),9)); allt.add(tuple(sorted((int(r['l1']),int(r['l2']),int(r['l3'])))))
with open(os.path.join(tabs,'hanke_torrilhon_comparison.tex'),'w') as f:
    f.write("% generated by revision/scripts/comparison_tables.py -- do not edit\n\\begin{tabular}{@{}crrc@{}}\n\\toprule\n$l_1$ & channels & entries & largest relative residual \\\\\n\\midrule\n")
    for l1 in sorted(g): f.write(f"{l1} & {g[l1]['ch']} & {g[l1]['n']} & {sci(g[l1]['res'])} \\\\\n")
    f.write(f"\\midrule\nall & {tot_ch} & {tot_n} & {sci(tot_res)} \\\\\n\\bottomrule\n\\end{{tabular}}\n")
print(f"HT: {tot_ch} channels, {tot_n} entries, max residual {tot_res:.1e}; distinct factors {len(allf)} vs distinct sorted triples {len(allt)}")
# (2)
rows=list(csv.DictReader(open(os.path.join(data,'maxwell_degree_rule.csv'))))
with open(os.path.join(tabs,'maxwell_degree_rule.tex'),'w') as f:
    f.write("% generated by revision/scripts/comparison_tables.py -- do not edit\n\\begin{tabular}{@{}lcc@{}}\n\\toprule\nTensor & padding & largest forbidden entry (relative) \\\\\n\\midrule\n")
    for r in rows:
        if r['case'].startswith('fresh'): f.write(f"assembled for this test, $\\kmax=4$, $\\lmax=4$ & {r['case'].split('pad=')[1]} & {sci(float(r['ratio']))} \\\\\n")
    for r in rows:
        if r['case']=='precalc K=4 L=6': f.write(f"tensor of the spectrum and Galilean tests, $\\kmax=4$, $\\lmax=6$ & 20 & {sci(float(r['ratio']))} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(os.path.join(tabs,'maxwell_degree_rule.tex')).read())
# (3) projection error of the initial data of Sec. 5.3.3 (from initial_data_projection.csv)
rows=list(csv.DictReader(open(os.path.join(data,'initial_data_projection.csv'))))
Ks=[4,6,8,10]; Ls=[8,12,20]
with open(os.path.join(tabs,'initial_data_projection.tex'),'w') as f:
    f.write("% generated by revision/scripts/comparison_tables.py -- do not edit\n\\begin{tabular}{@{}c"+"c"*len(Ls)+"c"+"c"*len(Ls)+"@{}}\n\\toprule\n")
    f.write(" & \\multicolumn{%d}{c}{bi-Gaussian} & & \\multicolumn{%d}{c}{discontinuous} \\\\\n" % (len(Ls),len(Ls)))
    f.write("\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}\n" % (1+len(Ls), 3+len(Ls), 2+2*len(Ls)))
    f.write("$\\kmax$ & " + " & ".join(f"$\\lmax={L}$" for L in Ls) + " & & " + " & ".join(f"$\\lmax={L}$" for L in Ls) + " \\\\\n\\midrule\n")
    val={(r['case'],int(r['K']),int(r['L'])):float(r['relL2err']) for r in rows}
    for K in Ks:
        f.write(f"{K} & " + " & ".join(sci(val[('bigaussian',K,L)]) for L in Ls) + " & & " + " & ".join(sci(val[('discontinuous',K,L)]) for L in Ls) + " \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(os.path.join(tabs,'initial_data_projection.tex')).read())
