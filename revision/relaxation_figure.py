"""Item 20: figure + convergence table for the bi-Gaussian and discontinuous relaxation (hard spheres).
Reads revision/data/relax_<case>_k<K>_l<L>.csv (from revision_initial_data_dynamics.m)."""
import csv, os, glob, sys
def fmtint(n): return f"{n:,}" if n>=10000 else str(n)
import numpy as np
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
here=os.path.dirname(os.path.abspath(__file__)); data=os.path.join(here,'data'); figdir=os.path.join(here,'figures')
def load(case,K,L):
    fn=os.path.join(data,f'relax_{case}_k{K}_l{L}.csv')
    if not os.path.exists(fn): return None
    r=np.genfromtxt(fn,delimiter=',',names=True); return r
runs=sorted(set((int(os.path.basename(f).split('_k')[1].split('_l')[0]),int(os.path.basename(f).split('_l')[1].split('.')[0])) for f in glob.glob(os.path.join(data,'relax_*_k*_l*.csv'))))
print("available (K,L):",runs)
Ls=sorted(set(L for K,L in runs)); Lmax=max(Ls); Ks=sorted(set(K for K,L in runs if L==Lmax))
fig,ax=plt.subplots(2,2,figsize=(9,6.2))
spec=[('bigaussian','sigma_zz',r'$\sigma_{zz}$',ax[0,0]),('bigaussian','m4',r'$\langle v^4\rangle$',ax[0,1]),('discontinuous','q_z',r'$q_z$',ax[1,0]),('discontinuous','sigma_zz',r'$\sigma_{zz}$',ax[1,1])]
for case,col,lab,a in spec:
    for K in Ks:
        r=load(case,K,Lmax)
        if r is None: continue
        a.plot(r['tau'],r[col],label=rf'$K_{{\max}}={K}$')
    a.set_xlabel(r'$\tau$'); a.set_ylabel(lab); a.set_title(f"{'bi-Gaussian' if case=='bigaussian' else 'discontinuous'}, $L_{{\\max}}={Lmax}$",fontsize=10); a.grid(alpha=.3)
ax[0,0].legend(fontsize=8)
plt.tight_layout(); out=os.path.join(figdir,'fig_relaxation_cases.pdf'); plt.savefig(out); print("figure",out)
def sci(x):
    if x<1e-15: return "$<10^{-15}$"
    e=int(np.floor(np.log10(x))); m=x/10**e
    return f"${m:.1f}\\times 10^{{{e}}}$"
# convergence table: max |difference| over tau in [0,6] between each run and the finest (Kmax, Lmax) run
with open(os.path.join(here,'tables','relaxation_convergence.tex'),'w') as f:
    f.write("% generated by revision/scripts/relaxation_figure.py -- do not edit\n\\begin{tabular}{@{}llrrrr@{}}\n\\toprule\nCase & $(\\kmax, \\lmax)$ & $\\dof$ & $\\max|\\Delta\\sigma_{zz}|$ & $\\max|\\Delta q_z|$ & $\\max|\\Delta\\langle v^4\\rangle|$ \\\\\n\\midrule\n")
    for case in ['bigaussian','discontinuous']:
        Kref=max(Ks); ref=load(case,Kref,Lmax)
        for K,L in runs:
            r=load(case,K,L)
            if r is None or (K,L)==(Kref,Lmax): continue
            d=[np.max(np.abs(r[c]-ref[c])) for c in ['sigma_zz','q_z','m4']]
            f.write(f"{'bi-Gaussian' if case=='bigaussian' else 'discontinuous'} & ({K}, {L}) & {fmtint((K+1)*(L+1)**2)} & {sci(d[0])} & {sci(d[1])} & {sci(d[2])} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(os.path.join(here,'tables','relaxation_convergence.tex')).read())
