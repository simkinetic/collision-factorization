"""Item 17: single-core execution time of the contraction orders for K_max = 4, 6, 8 at L_max = 12
(revision/data/timing_kscan.csv, from revision_timing_kscan.m, Apple M2 Pro). Also the operation-count
ratio of Eq. (ratio_naive_angular) for comparison with the measured naive/angular ratio."""
import csv, os
def fmtint(n): return f"{n:,}" if n>=10000 else str(n)
here=os.path.dirname(os.path.abspath(__file__)); rows=list(csv.DictReader(open(os.path.join(here,'data','timing_kscan.csv'))))
out=os.path.join(here,'tables','timing_kscan.tex')
def ms(x): x=float(x); return '--' if x!=x else f"{1e3*x:.1f}"
with open(out,'w') as f:
    f.write("% generated by revision/scripts/timing_table.py -- do not edit\n\\begin{tabular}{@{}crrrrrrcc@{}}\n\\toprule\n$\\kmax$ & $\\dof$ & \\multicolumn{4}{c}{Time per evaluation [ms]} & \\multicolumn{2}{c}{Term-by-term / angular-first} \\\\\n\\cmidrule(lr){3-6}\\cmidrule(lr){7-8}\n & & Dense & Term-by-term & Radial-first & Angular-first & measured & operation count \\\\\n\\midrule\n")
    for r in rows:
        K=int(r['K']); NK=K+1; NG=int(r['N_G']); NS=int(r['N_S'])
        pred=NG*NK**3/(NG*NK**2+NS*NK**3)
        f.write(f"{K} & {fmtint(int(r['N']))} & {ms(r['t_dense'])} & {ms(r['t_naive'])} & {ms(r['t_radial'])} & {ms(r['t_angular'])} & {float(r['t_naive'])/float(r['t_angular']):.1f} & {pred:.1f} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(out).read())
