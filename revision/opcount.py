import csv, os
def fmtint(n): return f"{n:,}" if n>=10000 else str(n)
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'tables'); os.makedirs(out, exist_ok=True)
def sci(x):
    e=int(math.floor(math.log10(x))); m=x/10**e
    return f"${m:.2f}\\times 10^{{{e}}}$"
