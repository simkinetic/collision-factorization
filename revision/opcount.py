import numpy as np, math
# Exact operation counts of the four contraction orders for
#  (A) tensor-product truncation k<=K, l<=L   and (B) total-degree truncation 2k+l<=M.
# Per Gaunt nonzero (real selection rule), per (channel,q1) slice.
def channels(L):
    for l1 in range(L+1):
        for l2 in range(L+1):
            for l3 in range(abs(l1-l2), min(l1+l2,L)+1):
                if (l1+l2+l3)%2==0: yield l1,l2,l3
def ng_channel(l1,l2,l3):
    m2=np.arange(-l2,l2+1)[:,None]; m3=np.arange(-l3,l3+1)[None,:]
    a2=np.abs(m2); a3=np.abs(m3); neg=(m2<0).astype(int)+(m3<0)
    cnt=np.zeros_like(a2+a3)
    for a1 in (a2+a3, np.abs(a2-a3)):
        ok=(a1<=l1)
        # m1 sign choices: if a1==0 only m1=0 (nonneg) -> need neg even; else two signs: exactly one of them makes neg count even
        cnt+= ok & (a1==0) & (neg%2==0)
        cnt+= ok & (a1>0)
    # avoid double counting when a2+a3 == |a2-a3| (i.e. one of them zero): handled by distinct a1 unless equal
    dup=(a2+a3==np.abs(a2-a3))
    cnt-= dup*(( (a2+a3)<=l1 )*( ((a2+a3)>0) + ((a2+a3)==0)*(neg%2==0) ))
    return int(cnt.sum())
def counts(Kfun, L):
    naive=rad=ang_g=ang_s=dense=0
    NG=NS=0
    for c in channels(L):
        K1,K2,K3=(Kfun(l) for l in c); ng=ng_channel(*c); NG+=ng; NS+=2*c[0]+1
        naive += ng*K1*K2*K3
        ang_g += ng*K2*K3
        ang_s += (2*c[0]+1)*K1*K2*K3
    return NG,NS,naive,ang_g,ang_s
print("(A) tensor-product truncation, K=4 (Kmax), vs L: naive=N_G K^3, angular=N_G K^2 + N_S K^3")
for L in [6,8,10,12,13,16]:
    NG,NS,nv,ag,as_=counts(lambda l:5,L)
    print(f" L={L:>2} N_G={NG:>8} N_S={NS:>6} naive={nv:>10} angular={ag+as_:>9} (gaunt {ag}, slice {as_}) ratio={nv/(ag+as_):.2f}")
print("(B) total-degree truncation 2k+l<=M, K(l)=floor((M-l)/2)+1, L=M")
rows=[]
for M in [8,12,16,20,24,28,32]:
    NG,NS,nv,ag,as_=counts(lambda l:(M-l)//2+1, M)
    N=(M+1)*(M+2)*(M+3)//6
    rows.append((M,N,nv,ag+as_))
    print(f" M={M:>2} N={N:>5} naive={nv:>12} angular={ag+as_:>11} ratio={nv/(ag+as_):.2f}")
print("local log-log slopes (exponent in M):")
for (M0,_,n0,a0),(M1,_,n1,a1) in zip(rows,rows[1:]):
    print(f" M {M0}->{M1}: naive {math.log(n1/n0)/math.log(M1/M0):.2f}  angular {math.log(a1/a0)/math.log(M1/M0):.2f}")

