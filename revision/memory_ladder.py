"""Item 21: memory table at matched numbers of coefficients (M = 20, 1771 coefficients).
Rows: dense tensor; azimuthally selected tensor (Cai-Fan-Wang 2020, as published); impact x coupling
tensor (Hanke-Torrilhon 2023, general kernel, as published); this work for the tensor-product truncation
K=10, L=20, the tightest superspace of 2k+l <= 20; and this work reduced to the total-degree set, storing
per channel only the radial degrees k_i <= (M - l_i)/2. Our accounting: 20 bytes per Gaunt nonzero
(3 x uint32 + 1 x double) and 8 bytes per entry of R. N_G at L=20 from the selection-rule count
(overcounts the measured nonzeros by < 0.3%)."""
import os, sys
def fmtint(n): return f"{n:,}" if n>=10000 else str(n)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from opcount import channels, ng_channel
MB = 1e6; GB = 1e9; M = 20
N20 = (M+1)*(M+2)*(M+3)//6
cs = list(channels(M)); NT = len(cs); NG = sum(ng_channel(*c) for c in cs)
K = M//2
N_sup = (K+1)*(M+1)**2
R_sup = (K+1)**3 * NT
R_red = sum(((M-c[0])//2+1)*((M-c[1])//2+1)*((M-c[2])//2+1) for c in cs)
rows = [
 ("Dense Cartesian tensor", r"$2k+l \le 20$", N20, 8*N20**3),
 (r"Azimuthally selected tensor \citep{cai:2020}", r"$2k+l \le 20$", N20, 784*MB),
 (r"Impact $\times$ coupling tensor \citep{hanke:2023}", r"$2k+l \le 20$", N20, 12.2*MB + 38*MB),
 (r"$\Rtens$ + COO Gaunt tensor (this work)", r"$\kmax = 10,\ \lmax = 20$", N_sup, NG*20 + 8*R_sup),
 (r"$\Rtens$ + COO Gaunt tensor (this work), reduced", r"$2k+l \le 20$", N20, NG*20 + 8*R_red),
]
def fmt(b): return f"{b/GB:.1f}\\,GB" if b >= GB else f"{b/MB:.1f}\\,MB"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tables', 'memory_ladder.tex'); os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write("% generated by revision/scripts/memory_ladder.py -- do not edit\n\\begin{tabular}{@{}llrr@{}}\n\\toprule\nRepresentation & Truncation & $\\dof$ & Memory \\\\\n\\midrule\n")
    for m, t, n, b in rows: f.write(f"{m} & {t} & {fmtint(n)} & {fmt(b)} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(f"N_T(20)={NT}  N_G(20)={fmtint(NG)}  R_sup={fmtint(R_sup)}  R_red={fmtint(R_red)}")
for m, t, n, b in rows: print(f"{m:55s} {t:28s} {n:6,d} {fmt(b):>10s}")

# memory scaling table at K=4 (replaces the inline table): N_G from the measured counts
paperNG={6:6460,8:23621,10:65913,12:154330,16:601569}
out2=os.path.join(os.path.dirname(os.path.abspath(__file__)),'tables','memory_scaling.tex')
with open(out2,'w') as f:
    f.write("% generated by revision/scripts/memory_ladder.py -- do not edit\n\\begin{tabular}{@{}rrrrrr@{}}\n\\toprule\n$\\lmax$ & $\\dof$ & $\\numG$ & Dense tensor & Factorized & Ratio \\\\\n\\midrule\n")
    for L in [6,8,10,12,16]:
        cs=list(channels(L)); NT=len(cs); N=5*(L+1)**2; dense=8*N**3; fact=paperNG[L]*20+8*125*NT
        d=f"{dense/GB:.2f}\\,GB" if dense>=GB else f"{dense/MB:.0f}\\,MB"
        r=fact/dense; e=int(f"{r:e}".split('e')[1]); m=r/10**e
        f.write(f"{L} & {fmtint(N)} & {fmtint(paperNG[L])} & {d} & {fact/MB:.2f}\\,MB & ${m:.1f}\\times 10^{{{e}}}$ \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(out2).read())
