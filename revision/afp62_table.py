"""Item 15: compare generalized eigenvalues of the linearized hard-sphere operator (ours, from
revision_afp62_eigenvalues.m -> revision/data/afp62_generalized_eigenvalues.csv) with the rigid-sphere
eigenvalues lambda_rl of Alterman, Frankowski & Pekeris (1962), Table 2. Their eq. (21) gives
J phi_rl = -a^2 sqrt(pi) (1 + 1/lambda_rl) nu phi_rl, so the basis- and unit-independent quantity is
(1 + 1/lambda_rl) / (1 + 1/lambda_02), to be compared with our mu_rl / mu_02."""
import csv, os
here=os.path.dirname(os.path.abspath(__file__))
# lambda_rl transcribed from AFP62 Table 2 (pages 300-316 of the journal): {(l,r): lambda}
afp={(0,0):-1.0,(0,1):-1.0,(0,2):-1.579716327,(0,3):-2.131484828,(0,4):-2.673311353,(0,5):-3.209419713,(0,6):-3.741668242,(0,7):-4.271082056,
     (1,0):-1.0,(1,1):-1.625196643,(1,2):-2.177412284,(1,3):-2.716920504,
     (2,0):-2.421826301,(2,1):-2.823575678,(2,2):-3.272265606,(2,3):-3.749125690,
     (3,0):-4.444491523,(3,1):-4.782799886,(3,2):-5.165299559,(3,3):-5.574892473,(3,4):-5.998384196,(3,5):-6.425978993,(3,6):-6.853012310,(3,7):-7.282820997,
     (4,0):-7.132479509,(4,1):-7.396957101,(4,2):-7.703612688,(4,3):-8.044163666,(4,4):-8.411454401,(4,5):-8.799496086,(4,6):-9.203565385,(4,7):-9.620245361,(4,8):-10.04729193,(4,9):-10.48332224}
extra=os.path.join(here,'afp62_extra.csv')   # optional additional (l,r,lambda) rows
if os.path.exists(extra):
    for r in csv.DictReader(open(extra)): afp[(int(r['l']),int(r['r']))]=float(r['lambda'])
ours={}
for r in csv.DictReader(open(os.path.join(here,'data','afp62_generalized_eigenvalues.csv'))):
    ours[(int(r['l']),int(r['r']))]=float(r['mu'])
mu02=ours[(2,0)]; g=lambda lam: 1+1/lam; ref02=g(afp[(2,0)])
rows=[]
for (l,r),lam in sorted(afp.items()):
    if (l,r) not in ours: continue
    a=g(lam)/ref02; o=ours[(l,r)]/mu02
    rows.append((l,r,lam,a,o,abs(o-a)/abs(a) if a!=0 else abs(o)))
print(f"{'l':>2} {'r':>2} {'lambda_rl':>14} {'AFP ratio':>12} {'ours':>12} {'rel diff':>10}")
for l,r,lam,a,o,d in rows: print(f"{l:>2} {r:>2} {lam:>14.9f} {a:>12.7f} {o:>12.7f} {d:>10.1e}")
nz=[d for l,r,lam,a,o,d in rows if a!=0]; print(f"max rel diff (nonzero modes): {max(nz):.1e}; entries: {len(rows)}")
out=os.path.join(here,'tables','afp62_eigenvalues.tex')
with open(out,'w') as f:
    f.write("% generated by revision/scripts/afp62_table.py -- do not edit\n\\begin{tabular}{@{}cccccc@{}}\n\\toprule\n$l$ & $r$ & $\\lambda_{rl}$ \\citep{alterman:1962} & $(1+1/\\lambda_{rl})/(1+1/\\lambda_{02})$ & $\\omega_{rl}/\\omega_{02}$ (this work) & rel.\\ diff. \\\\\n\\midrule\n")
    def sci(d):
        if d<1e-12: return "$<10^{-12}$"
        e=int(f"{d:e}".split('e')[1]); m=round(d/10**e)
        if m==10: m,e=1,e+1
        return f"${m}\\times 10^{{{e}}}$"
    for l,r,lam,a,o,d in rows:
        if r>3: continue
        f.write(f"{l} & {r} & ${lam:.9f}$ & {a:.7f} & {abs(o) if abs(o)<5e-8 else o:.7f} & {sci(d)} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print("written",out)
