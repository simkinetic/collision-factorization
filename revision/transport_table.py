"""Item 15: successive Chapman-Enskog approximations for hard spheres (viscosity l=2, heat conduction
l=1) from revision/data/coefficient_verification_transport.csv (revision_coefficient_verification.m),
against Pekeris & Alterman (1957) eqs (54), (49) and their infinite-order limits."""
import csv, os
here=os.path.dirname(os.path.abspath(__file__))
rows=list(csv.DictReader(open(os.path.join(here,'data','coefficient_verification_transport.csv'))))
out=os.path.join(here,'tables','transport_coefficients.tex')
# Reference: Cai & Torrilhon (2015). n=2..6: the exact fractions given after their eq. (5.8), evaluated to 13 digits;
# n=7..9: their Table 1 (10-11 digits). (Their Table 1 prints 1.0160059118 for n=4; the exact fraction
# 56934489009/56037556432 given in the same paper evaluates to 1.0160059188, which we use.)
from fractions import Fraction as Fr
ex_mu={2:Fr(205,202),3:Fr(1178769,1160344),4:Fr(56934489009,56037556432),5:Fr(639165671950185757,629082924175443840),6:Fr(23614270288651079628219833,23241652624351994320535296)}
ex_la={2:Fr(45,44),3:Fr(60989,59512),4:Fr(214747659,209482432),5:Fr(297319022628459,290011520447872),6:Fr(910415015606505287109,888025880354756521472)}
ref_mu={1:"1",**{n:f"{float(v):.10f}" for n,v in ex_mu.items()},7:"1.0160334713",8:"1.0160337922",9:"1.0160338905"}
ref_la={1:"1",**{n:f"{float(v):.9f}" for n,v in ex_la.items()},7:"1.02521632",8:"1.02521754",9:"1.02521794"}
with open(out,'w') as f:
    f.write("% generated by revision/scripts/transport_table.py -- do not edit\n")
    f.write("\\begin{tabular}{@{}lcccc@{}}\n\\toprule\nOrder $n$ & $f_\\mu^{(n)}$ & Reference & $f_\\kappa^{(n)}$ & Reference \\\\\n\\midrule\n")
    for r in rows:
        n=int(r['order'])
        if n>9: continue
        f.write(f"{n} & {float(r['f_mu']):.10f} & {ref_mu.get(n,'')} & {float(r['f_lambda']):.9f} & {ref_la.get(n,'')} \\\\\n")
    f.write("\\midrule\n$\\infty$ & & 1.016034 \\citep{pekeris:1957} & & 1.025218 \\citep{pekeris:1957} \\\\\n\\bottomrule\n\\end{tabular}\n")
print(open(out).read())
