"""Item 18: one-time assembly cost of the reduced tensor (sum-factorized 5D quadrature, padding 16,
hard spheres) on an Apple M2 Pro (12 cores, OpenMP), measured on the idle machine by
revision/scripts/assembly_timing.sh -> revision/data/assembly_times.csv."""
import csv, os
def fmtint(n): return f"{n:,}" if n>=10000 else str(n)
here=os.path.dirname(os.path.abspath(__file__))
rows={}   # all rows come from assembly_times.csv (measured on the idle machine, hard spheres, padding 16)
fn=os.path.join(here,'data','assembly_times.csv')
if os.path.exists(fn):
    for r in csv.DictReader(open(fn)): rows[(int(r['K']),int(r['L']))]=float(r['seconds'])
def NT(L):
    return sum(1 for l1 in range(L+1) for l2 in range(L+1) for l3 in range(abs(l1-l2),min(l1+l2,L)+1) if (l1+l2+l3)%2==0)
out=os.path.join(here,'tables','assembly_times.tex')
with open(out,'w') as f:
    f.write("% generated by revision/scripts/assembly_table.py -- do not edit\n\\begin{tabular}{@{}ccrrr@{}}\n\\toprule\n$\\kmax$ & $\\lmax$ & $\\dof$ & $\\numT$ & Assembly time [s] \\\\\n\\midrule\n")
    for (K,L),t in sorted(rows.items()):
        tt=f"{t:.0f}"
        f.write(f"{K} & {L} & {fmtint((K+1)*(L+1)**2)} & {fmtint(NT(L))} & {tt} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(out).read())
