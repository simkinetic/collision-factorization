"""Item 16: Galilean-invariance table from revision/data/galilean_invariance.csv (written by
revision_galilean_hardsphere.m in the code repo)."""
import csv, os
here=os.path.dirname(__file__); src=os.path.join(here,'data','galilean_invariance.csv')
rows=list(csv.DictReader(open(src)))
def sci(x):
    x=float(x)
    if x==0: return "$0$"
    e=int(f"{x:e}".split('e')[1]); m=x/10**e
    return f"${m:.2f}\\times 10^{{{e}}}$"
out=os.path.join(here,'tables','galilean_invariance.tex')
with open(out,'w') as f:
    f.write("% generated by revision/scripts/galilean_table.py -- do not edit\n")
    f.write("\\begin{tabular}{@{}lcccc@{}}\n\\toprule\nKernel & $|\\vmean|$ & $\\|Q\\|_2$ & $\\max |Q|$, stress modes & $\\max |Q|$, invariants \\\\\n\\midrule\n")
    for g,name in [("0.0","Maxwell molecules ($\\gamma=0$)"),("1.0","Hard spheres ($\\gamma=1$)")]:
        first=True
        for r in rows:
            if r['gamma']!=g: continue
            f.write(f"{name if first else ''} & {float(r['U']):.1f} & {sci(r['normQ'])} & {sci(r['maxQ_stress'])} & {sci(r['maxQ_inv'])} \\\\\n"); first=False
        if g=="0.0": f.write("\\midrule\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print(open(out).read())
